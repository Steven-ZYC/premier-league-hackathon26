function demo(
  id: string,
  title: string,
  competition: string,
  date: string,
  home: Team,
  away: Team,
  lines: string[],
): Match {
  const rawInput = lines.join("\n");
  const events = parseText(rawInput, home.name, away.name);
  const match: Match = {
    id,
    title,
    competition,
    date,
    home,
    away,
    events,
    coverage: "complete",
    source: "PitchPulse 产品演示 · 所有赛况均为虚构，不对应真实比赛",
    rawInput,
    demo: true,
    version: "",
    duration: Math.max(90, events.at(-1)!.activeMinute),
  };
  match.version = versionMatch(match);
  return match;
}

